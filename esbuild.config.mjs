import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { templatesModuleSource } from './scripts/templates-module.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

/**
 * Inlines every templates/*.md as the virtual module the plugin imports, so templates are
 * discovered from the folder instead of being registered one by one.
 */
const templatesPlugin = {
  name: 'templates',
  setup(build) {
    build.onResolve({ filter: /^virtual:templates$/ }, () => ({
      path: 'virtual:templates',
      namespace: 'templates',
    }));
    build.onLoad({ filter: /.*/, namespace: 'templates' }, () => ({
      contents: templatesModuleSource(),
      loader: 'js',
      // Needed so the absolute template imports in the generated module can be resolved.
      resolveDir: import.meta.dirname,
    }));
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    'node:sqlite',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2021',
  // Templates are markdown files inlined into the bundle at build time.
  loader: {
    '.md': 'text',
  },
  plugins: [templatesPlugin],
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
